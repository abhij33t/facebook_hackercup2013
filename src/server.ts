/**
 * Web Server — Interactive agent playground.
 *
 * Hosts a browser UI on a port. Streams agent execution in real-time
 * via Server-Sent Events so you can watch perceive→reason→plan→act→reflect live.
 *
 * Run:  npm start                         (port 3000)
 *       PORT=8080 npm start               (custom port)
 *       ANTHROPIC_API_KEY=sk-... npm start (pre-set key)
 */

